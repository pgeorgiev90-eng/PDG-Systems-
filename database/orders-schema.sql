CREATE TABLE IF NOT EXISTS pdg_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_number VARCHAR(40) NOT NULL UNIQUE,
 request_key CHAR(64) NOT NULL UNIQUE,
 customer_name VARCHAR(120) NOT NULL,
 email VARCHAR(254) NOT NULL,
 phone VARCHAR(40) NOT NULL,
 city VARCHAR(120) NOT NULL,
 address VARCHAR(500) NOT NULL,
 notes VARCHAR(2000) NOT NULL DEFAULT '',
 subtotal_cents BIGINT UNSIGNED NOT NULL,
 vat_cents BIGINT UNSIGNED NOT NULL,
 total_cents BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) NOT NULL DEFAULT 'EUR',
 status VARCHAR(30) NOT NULL DEFAULT 'new',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY idx_orders_created (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS pdg_order_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT UNSIGNED NOT NULL,
 product_id BIGINT UNSIGNED NOT NULL,
 code VARCHAR(190) NOT NULL,
 name VARCHAR(500) NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_cents BIGINT UNSIGNED NOT NULL,
 line_cents BIGINT UNSIGNED NOT NULL,
 KEY idx_order_items (order_id),
 CONSTRAINT fk_pdg_order FOREIGN KEY (order_id) REFERENCES pdg_orders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS pdg_checkout_limits (
 identifier_hash CHAR(64) PRIMARY KEY,
 window_start TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 attempt_count INT UNSIGNED NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
