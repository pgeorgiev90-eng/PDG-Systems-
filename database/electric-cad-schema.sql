CREATE TABLE IF NOT EXISTS pdg_electric_products (
 sku VARCHAR(40) PRIMARY KEY,
 product_json MEDIUMTEXT NOT NULL,
 price_cents BIGINT UNSIGNED NULL,
 active TINYINT NOT NULL DEFAULT 1,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pdg_electric_settings (
 setting_key VARCHAR(100) PRIMARY KEY,
 setting_value TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pdg_electric_busbar_rates (
 profile_key VARCHAR(60) PRIMARY KEY,
 width_mm DECIMAL(6,2) NOT NULL,
 thickness_mm DECIMAL(6,2) NOT NULL,
 price_per_m_cents BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS pdg_electric_enquiries (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 public_ref CHAR(24) NOT NULL UNIQUE,
 customer_name VARCHAR(160) NOT NULL,
 email VARCHAR(190) NOT NULL,
 phone VARCHAR(60) NOT NULL,
 project_name VARCHAR(200) NOT NULL,
 material_json MEDIUMTEXT NOT NULL,
 materials_cents BIGINT UNSIGNED NOT NULL,
 missing_prices INT UNSIGNED NOT NULL,
 labour_cents BIGINT UNSIGNED NULL,
 labour_admin BIGINT UNSIGNED NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'new',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
